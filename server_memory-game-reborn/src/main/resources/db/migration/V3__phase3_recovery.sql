-- Phase-3 recovery (P3): persistent match lifecycle for escrowed entry
-- fees plus the append-only coin ledger. Both are written inside the same
-- transactions as the balance mutations they describe.

create table if not exists pk_match_instance (
    id          bigint generated by default as identity primary key,
    match_id    varchar(255) not null,
    mode        varchar(255) not null,
    user_a      bigint,
    user_b      bigint,
    entry_fee   integer      not null,
    status      varchar(16)  not null,
    created_at  bigint       not null,
    settled_at  bigint
);

create unique index if not exists uk_pk_match_instance_match_id on pk_match_instance (match_id);
create index if not exists idx_pk_match_instance_status on pk_match_instance (status);

create table if not exists pk_coin_ledger (
    id          bigint generated by default as identity primary key,
    user_id     bigint       not null,
    match_id    varchar(255),
    amount      integer      not null,
    reason      varchar(32)  not null,
    created_at  bigint       not null
);

-- One movement per (user, reason, match); NULL match_id rows (welcome,
-- admin) are exempt from the rule on both H2 and PostgreSQL.
create unique index if not exists uk_pk_coin_ledger_entry on pk_coin_ledger (user_id, reason, match_id);
create index if not exists idx_pk_coin_ledger_user on pk_coin_ledger (user_id, created_at desc);
