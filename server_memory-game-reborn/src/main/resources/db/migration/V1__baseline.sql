-- Baseline schema (pre-hardening shape): mirrors the entities as they were
-- at the P1 review. Fresh databases start here; existing deployments are
-- baselined onto V1 by baseline-on-migrate and only receive V2+.

create table if not exists pk_user (
    id                  bigint generated by default as identity primary key,
    uuid                varchar(255) not null,
    token               varchar(255) not null,
    nickname            varchar(255) not null,
    elo                 integer      not null,
    wins                integer      not null,
    losses              integer      not null,
    draws               integer      not null,
    balance             integer      not null,
    created_at          bigint       not null,
    updated_at          bigint       not null,
    suspicion           integer      not null,
    restricted_matches  integer      not null,
    banned_until        bigint       not null,
    deleted             boolean      not null,
    practice_streak     integer,
    constraint uk_pk_user_uuid  unique (uuid),
    constraint uk_pk_user_token unique (token)
);

create table if not exists pk_match_record (
    id             bigint generated by default as identity primary key,
    match_id       varchar(255) not null,
    mode           varchar(255) not null,
    player_a       bigint       not null,
    nickname_a     varchar(255) not null,
    result_a       varchar(255) not null,
    score_a        integer      not null,
    player_b       bigint       not null,
    nickname_b     varchar(255) not null,
    score_b        integer      not null,
    elo_delta_a    integer      not null,
    created_at     bigint       not null,
    settled_at     bigint       not null,
    bot_opponent   boolean      not null
);

create table if not exists pk_season (
    id          bigint generated by default as identity primary key,
    season_index integer     not null,
    start_at    bigint       not null,
    end_at      bigint       not null,
    finalized   boolean      not null
);

create table if not exists pk_admin_audit (
    id           bigint generated by default as identity primary key,
    ts           bigint       not null,
    action       varchar(255) not null,
    params_json  varchar(255) not null,
    operator_ip  varchar(255) not null,
    result       varchar(255) not null
);
